"""Build a PyInstaller runtime hook from imports in the unobfuscated source.

PyInstaller cannot see imports inside an encrypted body.  It does analyze imports
in nested code objects of a custom runtime hook, so a never-called function can
make those modules available without importing them before the protected entry.
"""
from __future__ import annotations

import ast
import keyword
from pathlib import Path
from typing import Iterable, Mapping


def _module_name(relative: Path) -> str:
    parts = relative.with_suffix("").parts
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _source_files(source: Path) -> tuple[Path, list[Path]]:
    if source.is_file():
        if source.suffix != ".py":
            raise ValueError("source must be a .py file or directory")
        return source.parent, [source]
    if not source.is_dir():
        raise ValueError(f"source does not exist: {source}")
    files = sorted(source.rglob("*.py"))
    if not files:
        raise ValueError(f"no .py files under {source}")
    return source, files


def _valid_module(name: str) -> bool:
    return bool(name) and all(
        part.isidentifier() and not keyword.iskeyword(part) for part in name.split(".")
    )


def collect_pyinstaller_imports(
    source: str | Path, *, manifest: Mapping[str, str] | None = None,
    import_hook: bool = False, extra_imports: Iterable[str] = (),
) -> list[str]:
    """Return static imports to expose to PyInstaller's dependency analysis.

    Pass the manifest returned by ``obf_project`` with ``import_hook=True`` so
    embedded satellite modules are not collected again from the original tree.
    Runtime-computed imports need ``extra_imports``.
    """
    root, files = _source_files(Path(source))
    local_modules = {_module_name(path.relative_to(root)) for path in files}
    embedded = set()
    if import_hook:
        if manifest is None:
            raise ValueError("import_hook=True requires the obf_project manifest")
        embedded = {
            _module_name(Path(rel.replace("\\", "/")))
            for rel, role in manifest.items() if role == "protect"
        }

    found: set[str] = set()

    def add(module: str) -> None:
        if not _valid_module(module):
            raise ValueError(f"invalid module name: {module!r}")
        if module not in embedded:
            found.add(module)
        # The parent package still needs collection when a satellite is embedded.
        parts = module.split(".")
        for length in range(1, len(parts)):
            parent = ".".join(parts[:length])
            if parent in local_modules and parent not in embedded:
                found.add(parent)

    for path in files:
        relative = path.relative_to(root)
        parts = relative.with_suffix("").parts
        package_parts = parts[:-1]
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    add(alias.name)
            elif isinstance(node, ast.ImportFrom):
                if node.level:
                    if node.level > len(package_parts):
                        raise ValueError(f"relative import escapes package in {path}")
                    base = list(package_parts[:len(package_parts) - node.level + 1])
                    if node.module:
                        base.extend(node.module.split("."))
                    module = ".".join(base)
                else:
                    module = node.module or ""
                if module:
                    add(module)
                for alias in node.names:
                    candidate = f"{module}.{alias.name}" if module else alias.name
                    if alias.name != "*" and candidate in local_modules:
                        add(candidate)
    for module in extra_imports:
        add(module)
    return sorted(found)


def write_pyinstaller_hook(
    source: str | Path, hook_path: str | Path, *,
    manifest: Mapping[str, str] | None = None, import_hook: bool = False,
    extra_imports: Iterable[str] = (),
) -> list[str]:
    """Write a custom ``--runtime-hook`` for a protected PyInstaller entry.

    The hook defines a dormant function containing literal imports. PyInstaller
    collects those modules, while executing the hook does not import them or
    leave an extra frame on the entry's stack. Returns the collected names.
    """
    imports = collect_pyinstaller_imports(
        source, manifest=manifest, import_hook=import_hook,
        extra_imports=extra_imports,
    )
    path = Path(hook_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '"""PyInstaller dependency hook generated by pyobfuscator."""',
        "",
        "def _pyobfuscator_hidden_imports():",
    ]
    lines.extend(f"    import {module}" for module in imports)
    if not imports:
        lines.append("    pass")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return imports
