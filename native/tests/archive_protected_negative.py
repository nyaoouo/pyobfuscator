"""Wrong-key/state, malformed binding and source-ownership archive regressions."""

import copy
import json
from pathlib import Path
import re
import sys


def check_failures(args, directory: Path, run, materialize, protect):
    original = json.loads((directory / 'bindings.json').read_bytes())
    source = (directory / 'combined.ll').read_text()
    prepared = (directory / 'materialized.ll').read_text()
    protected = (directory / 'protected.ll').read_text()
    baseline_report = directory / 'baseline.coverage.json'
    baseline_report.write_bytes((directory / 'coverage.json').read_bytes())
    bad_manifest = directory / 'bad.bindings.json'
    rejected = directory / 'rejected.ll'
    for field, value in (('schema_version', True), ('plan_sha256', '0' * 64), ('unknown', 0)):
        bad = copy.deepcopy(original)
        bad[field] = value
        bad_manifest.write_text(json.dumps(bad), encoding='utf-8')
        materialize(bad_manifest, rejected, succeeds=False)
    for field, value in (('key_hex', '00'), ('wrapper', 'unrelated'), ('alignment', 3), ('index', 1)):
        bad = copy.deepcopy(original)
        bad['records'][0][field] = value
        bad_manifest.write_text(json.dumps(bad), encoding='utf-8')
        materialize(bad_manifest, rejected, succeeds=False)

    pool = re.sub(r'(^@[^\n]*package_bytes[^\n]*c")PYOBFAR1', r'\g<1>PYOBFAR0', source, count=1, flags=re.M)
    if pool == source:
        raise AssertionError('pool mutation did not reach actual generated bytes')
    altered = directory / 'altered.ll'
    altered.write_text(pool, encoding='utf-8')
    result = materialize(output=rejected, input_ir=altered, succeeds=False)
    if 'package bytes differ' not in result.stderr:
        raise AssertionError('linked pool tamper was not rejected at the binding boundary')

    name = original['records'][1]['wrapper']
    wrapper = re.search(rf'^define [^\n]*@{name}\([\s\S]*?^}}', source, re.M).group()
    reused = re.sub(r'(cache_)1(E)', r'\g<1>0\2', wrapper)
    if wrapper == reused:
        raise AssertionError('cache mutation did not reach a real wrapper')
    altered.write_text(source.replace(wrapper, reused), encoding='utf-8')
    result = materialize(output=rejected, input_ir=altered, succeeds=False)
    if 'cache' not in result.stderr:
        raise AssertionError('shared record cache was not rejected')

    missing_lane = re.sub(r', !pyobf\.archive\.key-slot !\d+', '', prepared, count=1)
    altered.write_text(missing_lane, encoding='utf-8')
    result = protect(input_ir=altered, output=rejected, succeeds=False)
    if 'not fully transformed' not in result.stderr:
        raise AssertionError('missing lane was not rejected through source coverage')
    failed_report = json.loads((directory / 'coverage.json').read_bytes())
    if not any(row.get('archive_sources') and row['status'] == 'unsupported' for row in failed_report['functions']):
        raise AssertionError('incomplete source had no failed coverage record')

    wrong_destination, count = re.subn(r'(call void @__pyobf_archive_[\w]+_0\(ptr [^,]+, ptr )@secret',
                                       r'\g<1>@empty', prepared)
    if count == 0:
        raise AssertionError('destination mutation did not reach real acquisitions')
    altered.write_text(wrong_destination, encoding='utf-8')
    protect(input_ir=altered, output=rejected, succeeds=False)
    altered.write_text(prepared.replace('"pyobf.archive.planned"', '"pyobf.archive.lost"'), encoding='utf-8')
    result = protect(input_ir=altered, output=rejected, succeeds=False)
    if 'prepared archive owner' not in result.stderr:
        raise AssertionError('source ownership marker loss was not rejected')

    no_support = run([str(args.opt), f'-load-pass-plugin={args.plugin}', '-passes=pyobf-native-cff',
                      '-pyobf-cff-markers=false', f'-pyobf-cff-config={directory / "config.json"}',
                      '-disable-output', str(directory / 'materialized.ll')], succeeds=False)
    if 'selected SDK support' not in no_support.stderr:
        raise AssertionError('archive silently left generated support unprotected')

    # Corrupt only one record's actual key; matching pool/schema cannot make it authenticate.
    wrong = copy.deepcopy(original)
    key = bytes.fromhex(wrong['records'][0]['key_hex'])
    wrong['records'][0]['key_hex'] = bytes([key[0] ^ 1]).hex() + key[1:].hex()
    bad_manifest.write_text(json.dumps(wrong), encoding='utf-8')
    wrong_materialized, wrong_protected = directory / 'wrong.materialized.ll', directory / 'wrong.protected.ll'
    materialize(bad_manifest, wrong_materialized)
    protect(input_ir=wrong_materialized, output=wrong_protected)
    wrong_dll = directory / 'wrong-key.dll'
    run([str(args.compiler), '-shared', str(wrong_protected), '-lbcrypt', '-o', str(wrong_dll)])
    child = run([str(directory / 'harness.exe'), str(wrong_dll), 'probe'], succeeds=False)
    if 'DATA-CONSUMED' in child.stdout:
        raise AssertionError('wrong archive key returned to the consumer')

    # Preserve relative-tree code, corrupt the independent archive-key mix in pointer().
    function = re.search(r'^define [^\n]*@pointer\([\s\S]*?^}', protected, re.M).group()
    corrupt, count = re.subn(r'(mul i32 [^,\n]+, )-1028477387\b', r'\g<1>-1028477385', function)
    if count < 8:
        raise AssertionError('state-key mutation did not reach archive key lanes')
    altered.write_text(protected.replace(function, corrupt), encoding='utf-8')
    altered_dll = directory / 'wrong-state.dll'
    run([str(args.compiler), '-shared', str(altered), '-lbcrypt', '-o', str(altered_dll)])
    for mode in ('probe', 'warm-probe'):
        child = run([str(directory / 'harness.exe'), str(altered_dll), mode], succeeds=False)
        if 'DATA-CONSUMED' in child.stdout:
            raise AssertionError('wrong state returned plaintext through a cold/ready cache')
    evidence = run([sys.executable, str(args.checker), str(args.objdump), str(altered_dll), str(baseline_report)], succeeds=False)
    if 'state-dependent archive keys' not in evidence.stderr:
        raise AssertionError('linked gate credited archive key lanes after their mix was changed')
